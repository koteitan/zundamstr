const BULLET_LINE = /^[ \t　]*(?:[-*+][ \t]|・)/u;

// 変換せずそのまま残す行を投稿全体から洗い出す。
// 行単位の手掛かり（前後の行との関係・字下げ・区切り記号）は
// 1文だけを見る zundaSentence では判断できないので、ここでまとめて集めるのだ
function linesToSkip(text) {
  const lines = text.split("\n");
  const skip = new Set();
  const body = lines.filter((l) => l.trim() !== "");
  // 材料・データの列挙ブロック（体言止めの短い行が3行以上続く範囲）
  const flags = lines.map(isListItemLine);
  let run = 0;
  for (let i = 0; i <= lines.length; i++) {
    if (i < lines.length && flags[i]) {
      run++;
      continue;
    }
    if (run >= 3) for (let k = i - run; k < i; k++) skip.add(lines[k]);
    run = 0;
  }
  if (body.length < 2) return skip;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].trim() === "") continue;
    if (INDENTED_LINE.test(lines[i])) skip.add(lines[i]);
    if (SEPARATOR_LINE.test(lines[i])) skip.add(lines[i]);
    // 次の（空行を挟まない）行が格助詞で始まるなら、この行は文の途中
    const next = lines[i + 1];
    if (next !== undefined && LEADING_PARTICLE.test(next)) skip.add(lines[i]);
    // 箇条書きを導く行が助詞「で」で終わっていれば、文はそこで終わっていない
    // （「でも一方で」＋「- みんなが…」）。中止法を断定に戻すルールの誤爆を防ぐのだ
    if (next !== undefined && BULLET_LINE.test(next) && /で[\s]*$/u.test(lines[i]))
      skip.add(lines[i]);
  }
  return skip;
}

// 日本語の文字（仮名・漢字・長音）。空白の両側がこれなら文の切れ目とみなす
const JP_CHAR = /[ぁ-ゖァ-ヺー々〆ヶ一-龯]/u;

// 日本語同士を挟む空白（半角・全角）で1行を文に切る。
// 「イヤだね 分散して…」のように句点の代わりに空白で文を並べる書き方に対応する。
// 「zundamstr も見て」「23 時」のようにラテン文字・数字が隣接する空白は
// 単なる語の区切りなので切らない。返り値は {body, gap} の配列で、gap は元の空白。
function splitByJapaneseSpace(s) {
  const segs = [];
  const re = /[ 　]+/gu;
  let start = 0;
  let m;
  while ((m = re.exec(s)) !== null) {
    const before = s[m.index - 1];
    const after = s[m.index + m[0].length];
    if (before && after && JP_CHAR.test(before) && JP_CHAR.test(after)) {
      segs.push({ body: s.slice(start, m.index), gap: m[0] });
      start = m.index + m[0].length;
    }
  }
  segs.push({ body: s.slice(start), gap: "" });
  return segs;
}

// 開いたままの括弧が残っているか（＝閉じ括弧を装飾として切り離したか）
function hasUnclosedBracket(s) {
  for (const [open, close] of BRACKETS) {
    let n = 0;
    for (const ch of s) {
      if (ch === open) n++;
      else if (ch === close) n--;
    }
    if (n > 0) return true;
  }
  return false;
}

// 話者ごとのキャラ語尾（「〜だよぷく」「〜てねぷく」）を、語彙を知らずに投稿から見つける。
// 未知の語尾は無限にあって列挙できないので、「同じ仮名列がその投稿の複数の文末に
// 繰り返し現れる」という事実だけを手掛かりにするのだ。
// 誤検出を避けるため、次の2つを両方満たすものだけをキャラ語尾とみなす:
//   (a) その文がどの ZUNDA_RULES にも当たらないこと
//       ＝既知の語尾なら「〜ないよ」「〜ですね」のように普通に処理できるので対象外
//   (b) 終助詞・断定の直後に付いていること
//       ＝キャラ語尾は文法的な文末の「後ろ」に足されるもので、
//         「〜を勉強する」の「する」のような述語そのものとはここで区別できるのだ
// 「な」は連体形の「な」（「そんなわけ」「〜ない」）と紛れるので目印に使わないのだ
const SFP_ANCHOR = "(?:だ|です|ます|みたい|[ねよわぞぜ])";
// 語尾そのものが普通の述語・助動詞であるものは、繰り返されても語尾ではないのだ
const PLAIN_ENDING = /^(?:のだ|なのだ|です|ます|ない|いる|ある|する|くる|した|など|から|けど|ので|のに)$/u;
function detectCharSuffix(text) {
  const sents = text
    .split(/[\n。．！!？?]/)
    .map((t) => t.trim())
    .filter((t) => t !== "");
  if (sents.length < 3) return ""; // 偶然の一致を避けるため短い投稿には使わない
  const counts = new Map();
  const anchored = new Set();
  for (const sent of sents) {
    const m = sent.match(DECOR_TAIL);
    let core = m ? sent.slice(0, sent.length - m[0].length) : sent;
    core = core.replace(/([ぁ-ゖ])ー+$/u, "$1");
    if (!core) continue;
    if (ZUNDA_RULES.some(([re]) => re.test(core))) continue; // (a)
    // 1文字の語尾は見ない。「訴えられない」の「い」のように活用の一部を
    // 語尾と誤認して語を食ってしまうからなのだ（キャラ語尾は必ず2文字以上ある）
    for (let n = 2; n <= 3 && core.length > n; n++) {
      const suf = core.slice(-n);
      if (!/^[ぁ-ゖァ-ヺ]+$/u.test(suf)) continue;
      counts.set(suf, (counts.get(suf) ?? 0) + 1);
      if (new RegExp(SFP_ANCHOR + suf + "$", "u").test(core)) anchored.add(suf); // (b)
    }
  }
  let best = "";
  for (const [suf, n] of counts)
    if (n >= 2 && anchored.has(suf) && !PLAIN_ENDING.test(suf) && suf.length > best.length)
      best = suf;
  return best;
}

// quoted = 歌詞・CM などの引用ブロック内の行。ルールに当たらない体言止めは触らない。
// 空白区切りの手前の文（＝文末とは限らない断片）にも同じ控えめな扱いを使う
function zundaSentence(raw, quoted = false, opts = {}) {
  // --- 変換しない行（誤変換より無変換のほうがよい） ---
  if (/^[\s]*[🎵🎶♪♫♬]/u.test(raw)) return raw; // 音符で始まる歌詞行
  if (/^　/.test(raw)) return raw; // 全角スペース字下げは歌詞・引用
  // 自分の文と併記された「>」の引用行は他人の発言なので触らない
  if (opts.partialQuote && QUOTE_LINE.test(raw)) return raw;
  if (COMMA_END.test(raw)) return raw; // 読点で終わる行は述語が次の行に続く
  // 格助詞で始まる行は前の行の続き（「…- 納品物を受け取る」＋「が自然そう」）。
  // 格助詞の直後を漢字・カタカナに限るのは「がんばる」のような語頭の仮名と
  // 区別するためなのだ
  if (/^[がをにへ][一-龯々ァ-ヺ]/u.test(raw.trim())) return raw;
  if (HEADING_MARK.test(raw)) return raw; // 「■ 流速計測」等の見出しラベル行
  if (/^\s*[[［【（(].*[\]］】）)]\s*$/u.test(raw)) return raw; // 括弧だけの見出し・ラベル行
  if (/([ぁ-ゖァ-ヺ])\1\1/u.test(raw)) return raw; // 同じ仮名の3連続は擬音・叫び
  // 1モーラを伸ばして1音で閉じただけの語は感動詞（「うーむ」「ふーん」「あーあ」）。
  // 語幹と言えるものが1文字しかなく、品詞を決める手がかりが無いのだ
  if (/^[ぁ-ゖ][ー〜～]+[ぁ-ゖ]$/u.test(raw.trim())) return raw;
  // 2〜3文字のまとまりが3回以上繰り返される行は擬音（「のすのすのすのす」）。
  // 意味のある語がこの形で3回続くことはないのだ
  if (/^([ぁ-ゖァ-ヺ]{2,3})\1{2,}$/u.test(raw.trim())) return raw;
  if (GREETING.test(raw.trim())) return raw; // 挨拶はそのまま
  if (SHORT_ELONGATED.test(raw.trim())) return raw; // 引き伸ばしただけの短い語はそのまま
  // 波ダッシュを語中に含む短いひらがなの断片は擬音（「うにょ〜ん」「ぷわ〜ん」）。
  // 長音符「ー」は「うまかったー」「ノーマン」のように語の一部でもあるので、
  // ここでは波ダッシュだけを手掛かりにするのだ
  if (/^[ぁ-ゖ][ぁ-ゖー〜～]{0,5}$/u.test(raw.trim()) && /[〜～]/u.test(raw))
    return raw;
  // 1〜2文字のひらがなだけの文は擬音・掛け声（「ぴ」「にゃ」）
  if (/^[ぁ-ゖ]{1,2}$/u.test(raw.trim())) return raw;
  // 半角記号の箇条書きは体言止めの断片が多いので控えめに扱う
  if (ASCII_BULLET.test(raw)) quoted = true;
  // 行単位の手掛かりで「文ではない」と分かった行はそのまま残す
  // （列挙ブロック・字下げ・区切り記号の行・次行が格助詞で始まる行）
  if (opts.skipLines && opts.skipLines.has(raw)) return raw;

  // 読点の前が丁寧語で終わっていれば、そこは文の切れ目なので先に常体へ直してから
  // 残りを処理する（「ねます、おやすみ〜」→「ねるのだ、おやすみなのだ〜」）。
  // 丁寧語に限るのは、「ロボからすると、」「そうそう、」のような普通の読点まで
  // 文末とみなすと、節の途中で語尾が付いて文が壊れるからなのだ
  // 疑問の「か」を伴う丁寧形（「〜ますか、」）も同じ文の切れ目なのだ
  const pol = raw.match(
    /^([^、，\n]*?(?:です|ます|ました|ません|でした)[かねよ]{0,2})([、，])/u,
  );
  if (pol) {
    const head = zundaSentence(pol[1], quoted, opts);
    if (head !== pol[1]) {
      // 疑問形に開いた節の直後の読点は「のだ？、」と記号が重なるので落とす
      const sep = /[？?]$/u.test(head) ? "" : pol[2];
      return zundaSentence(head + sep + raw.slice(pol[0].length), quoted, opts);
    }
  }

  // 日本語同士を挟む空白は句点の代わりなので、そこで区切って文ごとに変換する。
  // 手前の文は quoted 扱い（ルールに当たった時だけ変換）にして、
  // 「明日 東京に行く」の「明日」に語尾が付くような行き過ぎを防ぐ。
  const segs = splitByJapaneseSpace(raw);
  if (segs.length > 1) {
    return segs
      .map(
        (seg, k) =>
          zundaSentence(seg.body, k < segs.length - 1 ? true : quoted, opts) +
          seg.gap,
      )
      .join("");
  }

  // 末尾の注記（対応の取れた括弧）を装飾として切り離す
  let note = "";
  let s = raw;
  const nm = s.match(TRAILING_NOTE);
  if (nm) {
    note = nm[0];
    s = s.slice(0, s.length - note.length);
  }
  // 末尾の装飾を切り離してから語尾を変換し、装飾を戻す
  const m = s.match(DECOR_TAIL);
  let decorSym = m ? m[0] : "";
  let core = decorSym ? s.slice(0, s.length - decorSym.length) : s;
  if (!core) return raw; // 日本語コンテンツが無い行はそのまま
  // 日本語に直に続く英数字は語の一部なので本文に戻す（「手仕込みUDP」「衣80%」）。
  // 切り離したままだと語尾が語の途中に入って「手仕込みなのだUDP」になるのだ。
  // 「おもしろいw」の笑いは語ではないので対象外にする
  if (/^[A-Za-z0-9%％]+$/u.test(decorSym) && !/^[wWｗ]+$/u.test(decorSym) &&
      JP_CHAR.test(core[core.length - 1])) {
    core += decorSym;
    decorSym = "";
  }
  if (ONOMATOPOEIA.test(core)) return raw; // 引き伸ばした擬音はそのまま
  // 小書き仮名の引き伸ばしは、語尾を復元できる形のときだけ剥がして変換する
  let smallTail = "";
  if (STRETCH_TAIL.test(core)) {
    const bare = core.replace(/[ぁぃぅぇぉ]+$/u, "");
    if (!bare || !STRETCH_RESTORABLE.test(bare)) return raw;
    smallTail = core.slice(bare.length);
    core = bare;
  }
  const decor = smallTail + decorSym + note;

  // 「ラベル: 値」形式のデータ行（bot の集計・計測ログ）は表を壊すので変換しない
  if (/[:：]/.test(decor)) return raw;
  // 本文の後ろに「演算子＋数字」が続く行は数式・箇条書き風の断片（「らん漫 * 2」）。
  // ここに語尾を挿し込むと式が分断されるのだ。
  // 「らんまん * 4 = らん漫」のように本文が行末に来る形は装飾が空なので影響しない
  if (/^[ \t　]*[-+*/=×÷][ \t　]*[0-9０-９]/u.test(decor)) return raw;
  // 括弧の内側に語尾を挿し込まない
  if (hasUnclosedBracket(core)) return raw;
  // 感動詞・掛け声はそのまま
  if (INTERJECTION.test(core.trim())) return raw;
  // 注記や記号を外したら挨拶だけが残る行はそのまま（「おはようございますのすし(￣^￣)ゞ」）
  if (GREETING.test(core.trim())) return raw;

  // ひらがな＋長音で引き伸ばした感動詞・形容動詞語幹（「いやー」「やだー」）は
  // 長音を落としてから語尾を付ける（「いやーなのだ」の語尾衝突を防ぐ）。
  // 「コーヒー」「インイヤー」のようなカタカナ語の長音は語の一部なので落とさない。
  const stretched = /[ぁ-ゖ]ー+$/u.test(core);
  core = core.replace(/([ぁ-ゖ])ー+$/u, "$1");

  // この投稿の話者のキャラ語尾が付いていれば、その直前の終助詞ごと落としてから
  // 通常の変換にかける（「みたいぷく」→「みたいなのだ」）
  if (opts.charSuffix && core.length > opts.charSuffix.length &&
      core.endsWith(opts.charSuffix)) {
    const bare = core.slice(0, -opts.charSuffix.length).replace(/[ねよなわぞぜ]$/u, "");
    if (bare) core = bare;
  }

  for (const [re, rep] of ZUNDA_RULES) {
    if (re.test(core)) return core.replace(re, rep) + decor;
  }
  // 引用ブロック内でルール非該当の行は歌詞の一節・商品名・擬音なので触らない
  // （「名物かまど」→「名物かまどなのだ」「テロッテ～ン♪」の破壊を防ぐ）。
  // ただし見出し記号で始まる bot の定型投稿だけは、守りたいのがラベル・数値の
  // 体言止めの行なので、用言で言い切っている行は本文として下で変換するのだ
  if (quoted && !opts.botHeading) return raw;
  // ルール非該当時は末尾の文字種で出し分ける
  // 「つ」は漢字の直後だけ用言とみなす（「打つ」は動詞だが「やつ」「星2つ」は体言）
  if (/[一-龯々]つ$|[うくぐすずぬふぶむるいた]$/u.test(core))
    return core + "のだ" + decor; // 用言の終止形
  // 口語否定の「ん」（＝「ぬ」）は未然形に付く。ラ行五段の「わからん」、サ変の
  // 「せん」、関西の「へん」がその段なのだ。
  // 「こ」（カ変「こん」）を入れないのは「ぺこん」「ぽこん」のような擬音を
  // 巻き込んで「ぺこんのだ」を作ってしまうからなのだ
  if (/[らかせへ]ん$/u.test(core)) return core + "のだ" + decor;
  if (quoted) return raw; // bot の定型投稿に残った体言止めのラベル行
  // 長音を落とした形がえ段（命令形・仮定形・一段の活用語尾）や終助詞で終わるなら、
  // それは体言ではなく活用の途中・文末の飾りなのだ（「動けねー」「おはよー」
  // 「いそげいそげー」）。ここまでの規則にも用言の終止形にも当たらなかった以上、
  // 元の活用は復元できないので「なのだ」を付けずに無変換にする。
  // 引き伸ばした形容動詞語幹（「いやー」→「いや」）は や段・あ段で終わるので影響しない
  if (stretched && /[えけげせぜてでねへべめれよわな]$/u.test(core)) return raw;
  // 語中で長音符が3つ以上続く語は引き伸ばした叫び・感嘆（「えーーーん」）。
  // 実在の語にこの形は無く、伸ばす前の語形も復元できないので体言扱いにしないのだ
  // （「みれなーーーい」のように用言の終止形で終わる形は上で変換済み）
  if (/[ー〜～]{3,}/u.test(core)) return raw;
  // 音符で終わる体言止めの行は歌詞・CM・時報の擬音なので触らない
  // （「ポォ～ン♪」→「ポォ～ンなのだ♪」の破壊を防ぐ。「楽しかった♪」は上の用言で変換済み）
  if (NOTE_TAIL.test(raw)) return raw;
  // 末尾に URL が付く行は共有・告知の定型行で、本文は作品名や見出しのことが多い
  // （「荒野の七人／真昼の決闘 https://…」）。
  // 末尾に括弧の注記が付く行の本文も、作品名や形態名のことが多い
  // （「ゆうひかげ(じょうもんのすがた)」）。
  // どちらも用言で終わる普通の文は上で変換済みなので、残った体言止めには付けないのだ
  if (decor.includes(URL_MARK) || note) return raw;
  // 日本語に英数字が続く語（「手仕込みUDP」「衣80%」）は体言扱い
  if (/[A-Za-z0-9%％]$/u.test(core) && JP_CHAR.test(core))
    return core + "なのだ" + decor;
  if (/[ぁ-ゖ]$/u.test(core)) return core + "なのだ" + decor; // その他の仮名は体言扱い
  if (/[一-龯々ァ-ヺーゝゞ]$/u.test(core)) return core + "なのだ" + decor; // 漢字・カタカナ（体言）
  return core + decor; // それ以外はそのまま
}

function zundamonize(text) {
  // 投稿全体が助詞で始まる短い断片なら、前の投稿の続きなので触らない
  if (FRAGMENT_POST.test(text.trim())) return text;
  // 投稿全体がひらがなだけの短い語なら、挨拶・造語・擬音（「おはのす」「ぴ」）。
  // 挨拶を語彙リストで数え上げるとキリがないので、長さで一般に逃がすのだ
  if (/^[ぁ-ゖ]{1,4}$/u.test(text.trim())) return text;
  // 現代日本語の正書法は漢字仮名交じりで、助詞も送り仮名も仮名で書く。
  // 表意文字がこれだけ並んでいて仮名が1文字も無い投稿には、語尾を接ぎ木する
  // 相手（日本語の述語）が無いのでそのまま返すのだ。
  // 中国語の投稿がここに落ちるが、漢文調の日本語（「〜願上候」）も同じく無変換になる。
  // どちらも仮名の活用語尾が無く、機械的に語尾を差し替える手掛かりが無いのだ
  if (!/[ぁ-ゖァ-ヺ]/u.test(text) &&
      (text.match(/[一-龯々]/gu) ?? []).length >= 12) return text;


  // 音符で始まる行（歌詞・CM）か、見出し行（bot の定型投稿）が1行でもあれば、
  // 投稿全体を引用ブロックとみなす。
  // 引用中は用言・丁寧語の行だけ変換し、体言止めの行はそのまま残す。
  const lyric = LYRIC_LINE.test(text);
  const botHeading = !lyric && BOT_HEADING.test(text);
  const quoted = lyric || botHeading;

  // URL とハッシュタグは変換から保護する（タグ文字列を壊さないため）
  const kept = [];
  const hold = (mark) => (m) => {
    kept.push(m);
    return mark + (kept.length - 1) + mark;
  };
  let masked = text.replace(/https?:\/\/\S+/g, hold(URL_MARK));
  masked = masked.replace(
    /(^|[\s（(【「])([#＃][^\s#＃]+)/gu,
    (_m, pre, tag) => pre + hold(TAG_MARK)(tag),
  );

  // 材料・データの列挙ブロックに属する行を先に洗い出しておく。
  // 下の分割はマスク後の文字列を渡すので、こちらもマスク後で数えるのだ
  const skipLines = linesToSkip(masked);
  const charSuffix = detectCharSuffix(masked);
  // 引用行と自分の文が混在しているか（＝引用を保護すべきか）
  const bodyLines = masked.split("\n").filter((l) => l.trim() !== "");
  const quoteCount = bodyLines.filter((l) => QUOTE_LINE.test(l)).length;
  const partialQuote = quoteCount > 0 && quoteCount < bodyLines.length;

  // 文単位で分割（句読点・改行を区切りとして保持）し、各文を全部変換する
  // 全角ピリオド「．」を句点として使う書き手もいるので区切りに入れる。
  // 絵文字の「❓」「❗」も感嘆符・疑問符として文末に置かれるので同じ区切りにするのだ
  const parts = masked.split(/(\n|。|．|！|!|？|\?|❓|❗)/);
  let out = "";
  for (let i = 0; i < parts.length; i += 2) {
    const body = parts[i] ?? "";
    const delim = parts[i + 1] ?? "";
    if (body.trim() === "") {
      out += body + delim;
      continue;
    }
    let conv = zundaSentence(body, quoted, {
      skipLines, partialQuote, charSuffix, botHeading,
    });
    let d = delim;
    // 「〜か。」を疑問化すると「〜のだ？。」と終端記号が重なるので、
    // 変換後が疑問符で終わるなら区切りの句点・疑問符を落とす
    if (/[？?]$/.test(conv) && /^[。？?]$/.test(d)) d = "";
    out += conv + d;
  }

  // URL・ハッシュタグを復元
  return out.replace(
    new RegExp(`[${URL_MARK}${TAG_MARK}](\\d+)[${URL_MARK}${TAG_MARK}]`, "g"),
    (_, i) => kept[Number(i)],
  );
}

export { zundamonize, zundaSentence, ZUNDA_RULES };
