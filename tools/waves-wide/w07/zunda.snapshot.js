// ---------------------------------------------------------------------------
// zundamon transform (deterministic) — shared by main.js and tools/*
// ---------------------------------------------------------------------------
// 文末を機械的にずんだもん語尾へ変換する純粋関数。
// 上から順に最初にマッチした語尾だけを置換する（順序が重要）。
// 置換結果が元と同じルール（例 [/て$/, "て"]）は
// 「ここで打ち切ってこの文は変換しない」という意味の番人ルール。

// 「〜ます」の直前に来る連用形の末尾仮名を終止形へ戻す表
// （「お知らせします」→「お知らせする」、「感じます」→「感じる」）
const MASU_STEM = {
  // 五段：い段 → う段
  い: "う", き: "く", ぎ: "ぐ", ち: "つ", に: "ぬ",
  ひ: "ふ", び: "ぶ", み: "む", り: "る",
  // サ変・上一段
  し: "する", じ: "じる",
  // 一段：え段 → え段＋る
  え: "える", け: "ける", げ: "げる", せ: "せる", ぜ: "ぜる",
  て: "てる", で: "でる", ね: "ねる", へ: "へる", べ: "べる",
  め: "める", れ: "れる",
};
// 連用形＋ます を 終止形＋tail に直す置換関数を作る
const masu = (tail) => (_m, c) => MASU_STEM[c] + tail;
// 「ます」の直前に立てる仮名（＝連用形の語尾）。この表に無い仮名の「ます」は
// 「だます」「済ます」のように語幹の一部なので、ます形として扱ってはいけないのだ
const MASU_STEM_CLASS = `[${Object.keys(MASU_STEM).join("")}]`;

// 用言（動詞・形容詞）の終止形の末尾。ここで終わる語には「な」を挟まず「のだ」を付ける。
// 「う」は意向形・様態の「そう/よう/どう/ありがとう」と紛れるので、お段の直後を除く。
const YOGEN = "(?:[^おこごそぞとどのほぼもろよ]う|[くぐすずつぬぶむるいた])";
// 用言の終止形＋語尾 のルールを作る（$1 に終止形の末尾が入る）
const yr = (tail, rep) => [new RegExp(`(${YOGEN})${tail}$`), rep];
// 説明の「ん」（んです／んだ）の直前は用言の終止形か「な」「の」に限られる。
// この番人を挟まないと「みかんです」の語幹の「ん」まで削って「みかのだ」になる。
const nd = (tail, rep) => [new RegExp(`(${YOGEN}|な|の)ん${tail}$`), rep];

const ZUNDA_RULES = [
  // --- 特殊な語（誤った活用を防ぐため最優先） ---
  // 「すみません」の表記ゆれ（「すいません」・カタカナ書き）は同じ謝罪の定型句
  [/(?:すみません|すいません|スミマセン|スイマセン)$/, "すまないのだ"],
  [/ありがとうございます$/, "ありがとうなのだ"],
  // 「〜でございます」は丁寧な断定なので「なのだ」に落とす
  [/でございます$/, "なのだ"],
  // 挨拶・呼びかけの「〜ございます」は「ある」の丁寧形ではないので
  // 「おはようございます」→「おはようあるのだ」にしてはいけないのだ
  [/ございます$/, "なのだ"],
  // 末尾が「だ」でも断定ではない副詞。断定の「だ」ルールに食われて
  // 「まだ」→「まなのだ」になるのを防ぐ
  [/(まだ|いまだ|ただ|とんだ)$/, "$&なのだ"],

  // --- 五段動詞の音便＋過去の「んだ」「いだ」。説明の「んだ」より先に処理する ---
  // 説明の「んだ」の直前は必ず仮名（「行くんだ」「そうなんだ」）なので、
  // 漢字の直後の「んだ／いだ」は過去形とみなす（「読のだ」「泳いなのだ」を防ぐ）
  [/([一-龯々])んだ(?:よね|よな|よ|ね|な|わ|もん)?$/, "$1んだのだ"],
  [/([一-龯々])いだ(?:よね|よな|よ|ね|な|わ|もん)?$/, "$1いだのだ"],

  // --- 「ん」＋断定（んです/んだ 系）。「です」「だ」より先に処理する ---
  nd("ですか", "$1のだ？"),
  // 「〜んでしょう」は推量なので「のだろう」に開く。終助詞「ね」は残す
  // （「安定してるんでしょうねぇ」→「安定してるのだろうねぇ」）
  nd("でしょうね", "$1のだろうね"),
  nd("でしょう", "$1のだろう"),
  nd("ですね", "$1のだ"),
  nd("です", "$1のだ"),
  nd("だよね", "$1のだ"),
  // 「〜んだけどね」「〜んですけどぉ」。終助詞は落とさずに残す
  // （落とすと「楽しいのだけど」と逆接で終わって座りが悪いのだ）
  nd("だけど(ね|よ|な)?", "$1のだけど$2"),
  nd("ですけど(ね|よ|な)?", "$1のだけど$2"),
  nd("だ(?:よ|ね|な|わ|もん)", "$1のだ"),
  nd("だ", "$1のだ"),
  // 説明の「ん」に断定を伴わず終助詞だけが付いた形（「無くなってるんよな」）。
  // 「だ」系より後に置かないと「〜んだよ」を横取りしてしまう
  nd("(?:よね|よな|ね|な|よ|わ)", "$1のだ"),

  // --- 疑問（長い語尾を先に） ---
  [/ましたか$/, "たのだ？"],
  [/ませんか$/, "ないのだ？"],
  [/([てで])いますか$/, "$1いるのだ？"],
  [new RegExp(`(${MASU_STEM_CLASS})ますか$`), masu("のだ？")],
  [new RegExp(`(${MASU_STEM_CLASS})ましょうか$`), masu("のだ？")],
  // 用言に続く「でしょうか/だろうか」は「な」を挟まない
  yr("でしょうか", "$1のだ？"),
  [/でしょうか$/, "なのだ？"],
  // 準体助詞「の」＋丁寧語（「あかんのですか」→「あかんのだ？」）。
  // 「の」を残したまま「なのだ」を付けると「あかんのなのだ」になるのだ
  [/のですか$/, "のだ？"],
  // 用言＋です（「高いですか」→「高いのだ？」。「高いなのだ」を防ぐ）
  yr("ですか", "$1のだ？"),
  [/ですか$/, "なのだ？"],
  yr("だろうか", "$1のだ？"),
  [/だろうか$/, "なのだ？"],
  // 用言＋「かどうか」は疑問の従属節なので「のだろうか」に開く
  // （「終わるかどうかなのだ」のような途中で切れた形を防ぐ）
  yr("かどうか", "$1のだろうか"),
  [/かどうか$/, "かどうか"], // 用言以外は判別できないので無変換
  [/かしら$/, "のだ？"],
  // 意向形＋「かな」は「行こうかな」の形で活用が復元できないので触らない
  // （「変えようかなあ」→「変えようのだ？」のような破壊を防ぐ）
  [/[おこごそぞとどのほぼもろよ]うか(?:なあ|な)?$/, "$&"],
  // 説明の「の」＋「かな」。先に処理しないと「の」だけ残って
  // 「いったののだ？」と重複するのだ
  [/のか(?:なあ|な)$/, "のだ？"],
  [/のか$/, "のだ？"],
  // 「〜かな」「〜かい」は用言の終止形に付いた時だけ疑問として開く。
  // 直前の活用が崩れている形（「どうすっかな」「あんのんかい」）は終止形を
  // 復元できないので、削らずに無変換へ逃がす（番人）。
  yr("かな(?:あ)?", "$1のだ？"),
  [/かな(?:あ)?$/, "$&"],
  yr("かい", "$1のだ？"),
  [/かい$/, "$&"],
  // 方言の疑問「〜かや」も同じ扱い
  yr("かや", "$1のだ？"),
  // 詠嘆の「〜かあ」は問いかけではないので終助詞だけ落とす（「6時かあ」→「6時なのだ」）
  yr("かあ", "$1のだ"),
  [/かあ$/, "なのだ"],
  // 用言＋終助詞「か」は「か」を落として「のだ？」にする（「あかんかのだ」を防ぐ）
  [new RegExp(`(${YOGEN}|ん)か$`), "$1のだ？"],
  // 体言＋終助詞「か」も「か」を落として「なのだ？」にする（「映画かなのだ」を防ぐ）。
  // 漢字2文字以上に限るのは「静か」「確か」などの形容動詞語幹を削らないため。
  // カタカナを含めると「ネ確か」の「ネ確」を体言と誤認して「ネ確なのだ？」に壊すので、
  // 漢字だけにするのだ
  [/([一-龯々]{2,})か$/u, "$1なのだ？"],

  // --- 丁寧語 ---
  [/でした$/, "だったのだ"],
  [/ました$/, "たのだ"],
  [/ません$/, "ないのだ"],
  [new RegExp(`(${MASU_STEM_CLASS})ましょう$`), masu("のだ")],
  [/([てで])います[よね]?$/, "$1いるのだ"],
  [new RegExp(`(${MASU_STEM_CLASS})ます[よねわ]$`), masu("のだ")],
  [new RegExp(`(${MASU_STEM_CLASS})ます$`), masu("のだ")],
  [/でしょうね$/, "なのだ"],
  [/でしょう$/, "なのだ"],
  [/でしょ$/, "なのだ"],
  // 用言＋です（「高いですね」→「高いのだ」）
  yr("です(?:よね|よ|ね|わ)?", "$1のだ"),
  [/ですよね$/, "なのだ"],
  [/です(よ|ね|わ)$/, "なのだ"],
  // 準体助詞「の」＋です（「〜するのです」→「〜するのだ」）
  [/のです(?:ね|よ)?$/, "のだ"],
  [/です$/, "なのだ"],
  // 依頼。終助詞「よ/ね/な」が付いた形も同じ扱いにする（「買ってくださいよ」）
  [/てください(?:よ|ね|な)?$/, "てほしいのだ"],
  [/ください(?:よ|ね|な)?$/, "ほしいのだ"],
  // 「くださる」は「くれる」の敬語で依頼の意味なので「ください」と同じ扱いにする
  // （「ログボくださり」→「ログボほしいのだ」）
  [/くださ[りるれ]$/, "ほしいのだ"],
  // テ形＋「くれ」も依頼の命令形なので「ほしいのだ」に開く。
  // 「て」「で」を保存しないと「読んでくれ」が「読んてほしいのだ」になるのだ
  [/([てで])くれ(?:よ|ね|な)?$/, "$1ほしいのだ"],

  // --- のだ / なの 系（既にずんだもん語尾） ---
  // 既に「のだ」で終わっている文に終助詞が付いた形は終助詞だけ落とす
  // （「気がするのだよな」→「気がするのだ」。「のなのだ」になるのを防ぐ）
  [/のだ(?:よね|よな|よ|ね|な|わ|もん)$/, "のだ"],
  [/なのだ$/, "なのだ"],
  [/のだ$/, "のだ"],
  [/なの$/, "なのだ"],

  // --- 口語の断定 ---
  [/じゃない$/, "じゃないのだ"],
  // 用言＋「じゃん」は「のだ」、体言＋「じゃん」は「なのだ」
  yr("じゃん", "$1のだ"),
  [/じゃん$/, "なのだ"],
  [/だった$/, "だったのだ"],
  // 「〜たろ」は「〜ただろう」の縮約なので過去の「のだ」に戻す
  // （「言ったろ」→「言ったのだ」。下の「〜ろ」番人より先に処理するのだ）。
  // 「〜たろう」まで拾うと人名の「のすたろう」を壊すので「ろ」止まりにするのだ
  [/たろ$/, "たのだ"],
  // 方言の推量「〜じゃろ（＝だろう）」（「なんじゃろ」→「なんなのだ」）
  [/じゃろう?$/, "なのだ"],
  [/だろう$/, "なのだ"],
  [/だろ$/, "なのだ"],
  [/である$/, "なのだ"],
  [/だなあ$/, "なのだ"],
  [/だけど$/, "なのだけど"],
  [/だ(よね|よな|よ|ね|な|ぜ|ぞ|わ|もん)$/, "なのだ"],
  // 断定＋終助詞のあとにさらに仮名が続く形は、話者ごとのキャラ語尾
  // （「〜だよぷく」「〜だねゾ」）。未知の語尾は無限にあって列挙できないので、
  // 終助詞ごと落として素の断定に戻すのだ。
  // 続く仮名が「い」「ん」で始まる場合は「〜だない」「〜だなんて」のような
  // 普通の語尾なので除く（「ほどではまだない」を「ほどではまなのだ」に壊さないため）
  [/だ(?:よね|よな|よ|ね|な|ぜ|ぞ|わ)(?![いん])[ぁ-ゖ]{1,2}$/, "なのだ"],
  [/だ$/, "なのだ"],

  // --- 終助詞（用言の直後なら終助詞を落として「のだ」にする） ---
  // 方言の終助詞「ずら」は落とす（「寝るズラなのだ」の語尾二重を防ぐ）
  yr("(?:ずら|ズラ)", "$1のだ"),
  // 「あるな」→「あるのだ」「怖いな」→「怖いのだ」（「あるなのだ」を防ぐ）
  yr("(?:なあ|よね|よな|な|ね|よ|ぞ|ぜ|わ)", "$1のだ"),
  // 「〜ないと」は義務の言いさし。終助詞が付いた形もまとめて述語を補う
  // （「考えとかないとなあ」→「考えとかないといけないのだ」）。
  // 下の「と＋終助詞」ルールより先に置くのだ
  [/ないと(?:なあ|ねえ|な|ね)?$/, "ないといけないのだ"],
  // 撥音「ん」・拗音「ゃゅょ」・引用の「と」の直後は名詞の一部ではありえないので、
  // そこに続く終助詞は落として体言扱いにする
  // （「たいへんね」→「たいへんなのだ」「ねなきゃね」→「ねなきゃなのだ」）。
  // 「な」単体を入れると「みんな」「こんな」を、「わ」を入れると「しゃわ」を
  // 巻き込むので入れないのだ
  [/([んゃゅょと])(?:なあ|ねえ|よね|よな|ね|よ)$/, "$1なのだ"],
  // 理由の「〜から」＋終助詞（「連携取れていいからなぁ」→「〜いいからなのだ」）
  [/から(?:なあ|ねえ|な|ね|よ)$/, "からなのだ"],
  // 確認の「〜っけ」は「のだっけ」に開く（「なかったっけ」→「なかったのだっけ？」）
  [/っけ$/, "のだっけ？"],
  [/なあ$/, "なのだ"], // 「買わないとなあ」→「買わないとなのだ」

  // --- 形容動詞・体言的な語は「のだ」ではなく「なのだ」 ---
  [/(好き|すき|嫌い|きらい|綺麗|きれい|みたい|ぐらい|くらい)$/, "$&なのだ"],
  // 推量の「かも」。終助詞が付いた「かもな」「かもね」も同じ扱いにする
  // （「かもななのだ」と「な」が重なるのを防ぐ）
  [/かも(?:なあ|な|ね|よ)?$/, "かもしれないのだ"],
  // 連体形「ような」は「な」が重なるので1つにまとめる（「ようななのだ」を防ぐ）
  [/ような$/, "ようなのだ"],
  // 「そうか」「そうね」など指示語＋終助詞は終助詞を落とす
  [/(そう|こう|どう)(なあ|よね|か|ね|よ|な)$/, "$1なのだ"],

  // --- 助詞・活用形の誤接続を防ぐ ---
  [/まで$/, "までなのだ"], // 「ここまで」→「ここまでなのだ」
  [/ないで$/, "ないでほしいのだ"], // 「〜しないで」は依頼
  [/([んい])で$/, "$1で"], // 「読んで」「急いで」はテ形なので変換しない
  [/(ので|のに)$/, "$&"], // 接続助詞はそのまま
  // 限定・例示・不定の副助詞＋「で」は手段・範囲の中止法で文が続く
  // （「この3時間だけで」「日付の話かなんかで」を文末とみなさないのだ）
  [/(?:だけ|のみ|など|ほど|くらい|ぐらい|なんか|とか|か)で$/, "$&"],
  [/で$/, "なのだ"], // 「すごい状態で」の中止形は断定に戻す
  // 一段動詞の命令形は終止形に直してから付ける（「見せろのだ」を防ぐ）
  [/([えけげせぜてでねへべめれ])ろ$/, "$1るのだ"],
  // それ以外の「〜ろ」は五段の命令形（「がんばれ」系ではない「頑張ろ」）か
  // 意向形の口語短縮で、終止形が復元できないので触らない
  [/ろ$/, "$&"],
  // 五段の命令形＋終助詞「よ」は、え段をう段に戻せば終止形になる
  // （「己から振っていけよ」→「振っていくのだ」）
  [/([けげせてねべめれ])よ$/, (_m, c) => "くぐすつぬぶむる"["けげせてねべめれ".indexOf(c)] + "のだ"],
  // 一段の命令形「〜ろよ」は終止形を復元できないので触らない（「見てろよ」）
  [/([えぜでへろ])よ$/, "$&"],
  // サ変の口語命令「〜しな」は終止形に直す（「法人契約しな」→「法人契約するのだ」）。
  // 直前を漢字・カタカナに限るのは「はなしな」のような語中の「し」を拾わないため
  [/([一-龯々ァ-ヺ])しな$/, "$1するのだ"],
  // ラ行五段の未然形＋口語否定「ね」（「いらね」「わからね」「知らね」）は
  // 常体に戻してから付ける。他の行（「かね」「たね」「まね」）は名詞と紛れるので
  // ラ行だけにするのだ
  [/らね$/, "らないのだ"],
  // 間投助詞「さあ」で終わる行は呼びかけの途中なので触らない（「話題はさあ！」）
  [/さあ$/, "$&"],
  // 「〜ちゃお／〜じゃお」は「〜てしまう」の意向形の口語短縮なので終止形に戻す
  // （「呑んじゃおー」→「呑んじゃうのだ」）
  [/([じち])ゃお$/, "$1ゃうのだ"],
  // 意向形＋終助詞（「元気にすごそうね」「行こうよ」）は活用を復元できないので触らない
  [/[おこごそぞとどのほぼもろよ]う(?:ね|な|よ)$/, "$&"],
  // 様態・伝聞の「〜そう」は形容動詞的にふるまうので「なのだ」を付ける
  // （「かなり高そう」→「かなり高そうなのだ」）。
  // 漢字の直後に限るのは、ひらがなが続く「すごそう」「過ごそう」が
  // 様態か意向形か判別できず、「そうそう」まで巻き込むからなのだ
  [/([一-龯々])そう$/, "$&なのだ"],
  // 意向形「行こう」「しよう」や「〜そう」「ありがとう」は活用が判別できないので触らない
  [/([おこごそぞとどのほぼもろよ])う$/, "$&"],
  // 用言＋準体助詞「の」は説明・問いかけの言い切り（「ついてないんじゃないの」）。
  // 属格の「の」（「私の」）は用言で終わらないので下の番人に落ちて無変換になるのだ。
  // 番人の「の」より先に置かないと横取りされるのだ
  yr("の", "$1のだ？"),
  // 助詞・接続助詞で終わる行は文が途中なので変換しない（「時もなのだ」を防ぐ）。
  // 「と」は入れていない。「えんどれすえいと」のように「と」で終わる体言と
  // 区別できず、そちらを無変換にしてしまうからなのだ
  [/(から|けれども|けれど|けど|より|とか|たり|なら|ながら|まま|が|を|に|へ|は|の|も|て)$/, "$&"],
  // 漢字を含む語に続く「と」は引用・条件の言いさしなので触らない
  // （「〜であっても流入すると」）。漢字を要求するのは「てすとてすと」
  // 「えんどれすえいと」のような「と」で終わる体言を巻き込まないためなのだ
  [/[一-龯々][ぁ-ゖ]{0,2}と$/u, "$&"],
  // 全角スペースの後ろが数字と年月日だけの行末は、見出しに添えた日付ラベルなので
  // 断定の対象ではない（「…下半身露出未遂　６月２９日」）
  [/　[0-9０-９]+[年月日][0-9０-９年月日]*$/u, "$&"],
  yr("し", "$&"), // 「安いし」の接続助詞「し」
  // 漢字＋「し」は連用中止（「TKGみが増し」）か名詞なので、終止形を推測せず触らない
  [/([一-龯々])し$/, "$&"],
  // 「た」の直前が あ/う/お段 の仮名なら過去形ではありえないので体言扱い。
  // （過去の「た」の直前は い段・え段・「っ」・「ん」に限られる）
  // 「のすがた」→「のすがたなのだ」（「のすがたのだ」を防ぐ）
  [
    /([あかさたなはまやらわがざだばぱうくすつぬふむゆるぐずづぶぷおこそとのほもよろごぞどぼぽ])た$/,
    "$1たなのだ",
  ],
];

// 末尾の装飾（笑い・ラテン文字・数字・記号・絵文字・空白）を分離する
const DECOR_TAIL = /[\s\p{P}\p{S}\p{M}\p{Cf}A-Za-z0-9ｗ笑草]+$/u;
// URL・ハッシュタグを退避する不可視マーカー（どちらも書式制御文字 Cf なので
// 末尾の装飾として切り離される）。
// URL とハッシュタグを別のマーカーにするのは、末尾に URL が付く行だけを
// 「共有・告知の定型行」とみなしたいからなのだ。
// ハッシュタグは自分の文にタグを添えただけのことが多い（「ノルマ達成 #けだまメイズ」）
const URL_MARK = "⁠"; // WORD JOINER
const TAG_MARK = "﻿"; // ZERO WIDTH NO-BREAK SPACE
// 括弧の対応表（閉じ括弧の内側に語尾を挿し込まないための判定に使う）
const BRACKETS = [
  ["(", ")"], ["（", "）"], ["[", "]"], ["［", "］"],
  ["{", "}"], ["【", "】"], ["「", "」"], ["『", "』"], ["〈", "〉"],
];
// 感動詞・掛け声（そのまま残す）
const INTERJECTION =
  /^(よー*し|よし|さー*て|うん|ううん|はい|いいえ|おー*|ふー*|わー*い|あー*|えー*|おっけー|おつ)$/u;
// 挨拶（そのまま残す）。挨拶語＋仮名の伸ばし・崩しだけの行に限る
// （「おやすみすとら」「おはようございます」など。「おはよう、今日は…」は対象外）
const GREETING =
  /^(おはよ|おやすみ|こんにちは|こんばんは|ただいま|おかえり|いってきま|いってらっしゃ)[ぁ-ゖァ-ヺー～]*$/u;
// 記号＋空白で始まる見出し・ラベル行（bot の定型データ投稿の「■ 流速計測」など）。
// 空白を必須にして「●今日は寒い」のような普通の文まで巻き込まないようにする
const HEADING_MARK = /^\s*[■□▼▽▲△▶◀●○◎◆◇★☆][ \t　]/u;
// 音符で始まる行（歌詞・CM の引用）。1行でもあれば投稿全体が引用とみなす
const LYRIC_LINE = /^[ \t　]*[🎵🎶♪♫♬]/mu;
// 隅付き括弧【】や記号で始まる見出し行を持つ投稿は bot の定型投稿とみなす
// （「【緊急地震速報】08:40」「■ 流速計測」）。
// 中の体言止めの行（「宮崎県北部平野部」「震度 5-」）はラベルと数値であって文ではないので、
// 引用ブロックと同じ扱いにして、用言・丁寧語で終わる行だけを変換するのだ。
const BOT_HEADING = /^[ \t　]*(?:【[^】]{2,20}】|[■□▼▽▲△▶◀●○◎◆◇★☆][ \t　])/mu;
// 音符で終わる行（時報・CM の擬音「ポォ～ン♪」）。
// 「楽しかった♪」のように単なる気分の飾りのこともあるので行全体は捨てず、
// 用言・丁寧語で終わらない体言止めの行だけを引用とみなす（下の fallback で使う）
const NOTE_TAIL = /[🎵🎶♪♫♬][ \t　]*$/u;
// 波ダッシュで引き伸ばしたカタカナ語は擬音（「ポォ～ン」「テロッテ～ン」）。
// 「～」を含む語は実在の名詞ではありえないので、擬音とみなして無変換にする
const ONOMATOPOEIA = /[ァ-ヺ][ァ-ヺー～〜]*[～〜][ァ-ヺー～〜]*$/u;
// 小書き仮名で引き伸ばした感嘆・呼びかけの末尾（「まだぁ」「たのしぃ」「そうだよぉ」）。
// 述語の活用が崩れていて終止形を復元できない（「まだぁ」の「だ」は断定ではなく語の一部）ので、
// 誤変換を避けるために無変換にする。長音「ー」だけの引き伸ばし（「いやー」「コーヒー」）は
// 語の一部のこともあるので対象にしない（下の「ひらがな＋長音」の処理で別に扱う）。
const STRETCH_TAIL = /.[ぁ-ゖァ-ヺ][ぁぃぅぇぉ][ぁぃぅぇぉー～〜]*$/u;
// ただし引き伸ばしを落とした形が丁寧語（です／ます系）で終わるなら、語尾は
// 一意に復元できるので剥がして変換する（「〜ですけどぉ」「〜でしょうねぇ」）。
// 理由の「〜から」＋終助詞（「いいからなぁ」）も語尾が一意に決まるので剥がす。
// 終助詞を無条件に許すと「おもろいのになぁ」の「な」を体言と誤認して壊すので、
// 復元できると分かっている形だけに限るのだ
const STRETCH_RESTORABLE =
  /(?:です|ます|でしょう?|でした|ました|ませ[んょ])(?:ね|よ|か|けど|けれど)*$|から[なねよ]$/u;
// 短いひらがな語を長音・波ダッシュで引き伸ばしただけの文（「げっしょー」「おはのすー」
// 「かわい〜〜〜」）。引き伸ばす前の形（「かわい〜」＝「かわいい」）は復元できず、
// 長音を削ると「かわいのだ」「げっしょなのだ」と語を壊すので、丸ごと無変換にする。
// 4文字以下に限るのは、「うまかったー」のように活用が読み取れる長さの文まで
// 巻き込まないためなのだ。カタカナ語の長音（「インイヤー」「コーヒー」）は
// 語の一部なので対象外にする。
const SHORT_ELONGATED = /^[ぁ-ゖ]{1,4}[ー～〜]+[\s\p{P}\p{S}]*$/u;
// 投稿全体が助詞で始まるひらがなだけの短い断片（「のすがた」）。
// 直前の投稿に続けて書かれた体言止めなので、単独では文にならず変換できない。
// 語頭に立ちにくい「の」「を」に限る（「が」「に」「は」「も」だと
// 「がんばる」「はじまった」「もんぴ」のような普通の語を巻き込む）。
// 画像 URL や他の行を伴う投稿はそれだけで完結しているので対象外にする
// （「のりよし」＋画像のような短い題名を壊さないため）。
const FRAGMENT_POST = /^[のを][ぁ-ゖ]{1,4}$/u;
// 末尾に付いた対応の取れた括弧の注記（「幸せだよ(私の定義)」「おもしろい(笑)」）。
// 注記の内側に語尾を挿し込まないよう、装飾として切り離してから語尾を変換する。
// 顔文字の締めに使う踊り字（「(￣^￣)ゞ」）も一緒に切り離すのだ。
const TRAILING_NOTE =
  /[（(【［「『〈][^（(【［「『〈）)】］」』〉]*[）)】］」』〉][\sゝゞヽヾ]*$/u;
// 引用（メール・Markdown の「>」）で始まる行。
// 自分の文と併記された引用は他人の発言なので書き換えない（「> 検証しにくい」＋自分の返事）。
// ただし投稿全体が引用の場合は、その引用文こそが投稿の中身なので変換してよいのだ
const QUOTE_LINE = /^[ \t　]*[>＞]/u;
// 半角記号の箇条書き行。前後の行と1つの文をなす体言止めの断片であることが多いので
// （「だから marketplace 的には / - 公開募集で学習 / が自然そう」）、
// 引用ブロックと同じくルールに当たった時だけ変換する。
// 中黒「・」の箇条書きは完結した文が来るので対象にしないのだ
const ASCII_BULLET = /^[ \t　]*[-*+][ \t]/u;
// 文が途中で終わっている行（読点で終わる）。次の行に述語が続くので変換しない
const COMMA_END = /[、，][\s]*$/u;
// 材料・データの列挙ブロックを見つけるための行の判定。
// 助詞（文の骨格）を1つも含まず、用言の終止形でも終わらない短い行は、
// 文ではなくラベル・材料・作品名の断片なのだ（「梅みそ」「ショウガ」「震度 5-」）。
// ただし1行だけなら普通の体言止めの投稿（「ログボ」「やば言語」）なので、
// この形の行が3行以上続いた時にはじめて列挙ブロックとみなすのだ。
const PARTICLE = /[はがをにへともの]|から|まで|より/u;
const YOGEN_END = /[うくぐすずつぬふぶむるいたん]$/u;
function isListItemLine(line) {
  const t = line.replace(/[\s\p{P}\p{S}\p{M}\p{Cf}A-Za-z0-9]+$/u, "").trim();
  return t !== "" && t.length <= 12 && !PARTICLE.test(t) && !YOGEN_END.test(t);
}
// 行頭の格助詞＋体言。この行は前の行の名詞句を受けているので、前の行は文の途中なのだ
// （「株式会社　淀川に殴られる」＋「が爆誕するかも」）。
// 格助詞の直後を漢字・カタカナに限るのは「がんばる」のような語頭の仮名と区別するため
const LEADING_PARTICLE = /^[ \t　]*[がをにへ][一-龯々ァ-ヺ]/u;
// 空白で字下げされた行は引用・データの並び（bot のカード名など）
const INDENTED_LINE = /^[ 　][^\s]/u;
// タイトルと出典を記号で並べた行（「脱獄王 - ニコニコ動画」）。
// 空白で挟んだ区切り記号は日本語の文には現れない。
// ただし1行だけの投稿は「ぽわ / 2 = ぽか」のような本文そのものなので対象外にするのだ
const SEPARATOR_LINE = /[ \t　][-–—|｜/*+][ \t　]/u;
// 箇条書きの行（半角記号・中黒のどちらでも）
const BULLET_LINE = /^[ \t　]*(?:[-*+][ \t]|・)/u;

// 変換せずそのまま残す行を投稿全体から洗い出す。
// 行単位の手掛かり（前後の行との関係・字下げ・区切り記号）は
// 1文だけを見る zundaSentence では判断できないので、ここでまとめて集めるのだ
function linesToSkip(text) {
  const lines = text.split("\n");
  const skip = new Set();
  const body = lines.filter((l) => l.trim() !== "");
  // 材料・データの列挙ブロック（体言止めの短い行が3行以上続く範囲）
  const flags = lines.map(isListItemLine);
  let run = 0;
  for (let i = 0; i <= lines.length; i++) {
    if (i < lines.length && flags[i]) {
      run++;
      continue;
    }
    if (run >= 3) for (let k = i - run; k < i; k++) skip.add(lines[k]);
    run = 0;
  }
  if (body.length < 2) return skip;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].trim() === "") continue;
    if (INDENTED_LINE.test(lines[i])) skip.add(lines[i]);
    if (SEPARATOR_LINE.test(lines[i])) skip.add(lines[i]);
    // 次の（空行を挟まない）行が格助詞で始まるなら、この行は文の途中
    const next = lines[i + 1];
    if (next !== undefined && LEADING_PARTICLE.test(next)) skip.add(lines[i]);
    // 箇条書きを導く行が助詞「で」で終わっていれば、文はそこで終わっていない
    // （「でも一方で」＋「- みんなが…」）。中止法を断定に戻すルールの誤爆を防ぐのだ
    if (next !== undefined && BULLET_LINE.test(next) && /で[\s]*$/u.test(lines[i]))
      skip.add(lines[i]);
  }
  return skip;
}

// 日本語の文字（仮名・漢字・長音）。空白の両側がこれなら文の切れ目とみなす
const JP_CHAR = /[ぁ-ゖァ-ヺー々〆ヶ一-龯]/u;

// 日本語同士を挟む空白（半角・全角）で1行を文に切る。
// 「イヤだね 分散して…」のように句点の代わりに空白で文を並べる書き方に対応する。
// 「zundamstr も見て」「23 時」のようにラテン文字・数字が隣接する空白は
// 単なる語の区切りなので切らない。返り値は {body, gap} の配列で、gap は元の空白。
function splitByJapaneseSpace(s) {
  const segs = [];
  const re = /[ 　]+/gu;
  let start = 0;
  let m;
  while ((m = re.exec(s)) !== null) {
    const before = s[m.index - 1];
    const after = s[m.index + m[0].length];
    if (before && after && JP_CHAR.test(before) && JP_CHAR.test(after)) {
      segs.push({ body: s.slice(start, m.index), gap: m[0] });
      start = m.index + m[0].length;
    }
  }
  segs.push({ body: s.slice(start), gap: "" });
  return segs;
}

// 開いたままの括弧が残っているか（＝閉じ括弧を装飾として切り離したか）
function hasUnclosedBracket(s) {
  for (const [open, close] of BRACKETS) {
    let n = 0;
    for (const ch of s) {
      if (ch === open) n++;
      else if (ch === close) n--;
    }
    if (n > 0) return true;
  }
  return false;
}

// 話者ごとのキャラ語尾（「〜だよぷく」「〜てねぷく」）を、語彙を知らずに投稿から見つける。
// 未知の語尾は無限にあって列挙できないので、「同じ仮名列がその投稿の複数の文末に
// 繰り返し現れる」という事実だけを手掛かりにするのだ。
// 誤検出を避けるため、次の2つを両方満たすものだけをキャラ語尾とみなす:
//   (a) その文がどの ZUNDA_RULES にも当たらないこと
//       ＝既知の語尾なら「〜ないよ」「〜ですね」のように普通に処理できるので対象外
//   (b) 終助詞・断定の直後に付いていること
//       ＝キャラ語尾は文法的な文末の「後ろ」に足されるもので、
//         「〜を勉強する」の「する」のような述語そのものとはここで区別できるのだ
// 「な」は連体形の「な」（「そんなわけ」「〜ない」）と紛れるので目印に使わないのだ
const SFP_ANCHOR = "(?:だ|です|ます|みたい|[ねよわぞぜ])";
// 語尾そのものが普通の述語・助動詞であるものは、繰り返されても語尾ではないのだ
const PLAIN_ENDING = /^(?:のだ|なのだ|です|ます|ない|いる|ある|する|くる|した|など|から|けど|ので|のに)$/u;
function detectCharSuffix(text) {
  const sents = text
    .split(/[\n。．！!？?]/)
    .map((t) => t.trim())
    .filter((t) => t !== "");
  if (sents.length < 3) return ""; // 偶然の一致を避けるため短い投稿には使わない
  const counts = new Map();
  const anchored = new Set();
  for (const sent of sents) {
    const m = sent.match(DECOR_TAIL);
    let core = m ? sent.slice(0, sent.length - m[0].length) : sent;
    core = core.replace(/([ぁ-ゖ])ー+$/u, "$1");
    if (!core) continue;
    if (ZUNDA_RULES.some(([re]) => re.test(core))) continue; // (a)
    // 1文字の語尾は見ない。「訴えられない」の「い」のように活用の一部を
    // 語尾と誤認して語を食ってしまうからなのだ（キャラ語尾は必ず2文字以上ある）
    for (let n = 2; n <= 3 && core.length > n; n++) {
      const suf = core.slice(-n);
      if (!/^[ぁ-ゖァ-ヺ]+$/u.test(suf)) continue;
      counts.set(suf, (counts.get(suf) ?? 0) + 1);
      if (new RegExp(SFP_ANCHOR + suf + "$", "u").test(core)) anchored.add(suf); // (b)
    }
  }
  let best = "";
  for (const [suf, n] of counts)
    if (n >= 2 && anchored.has(suf) && !PLAIN_ENDING.test(suf) && suf.length > best.length)
      best = suf;
  return best;
}

// quoted = 歌詞・CM などの引用ブロック内の行。ルールに当たらない体言止めは触らない。
// 空白区切りの手前の文（＝文末とは限らない断片）にも同じ控えめな扱いを使う
function zundaSentence(raw, quoted = false, opts = {}) {
  // --- 変換しない行（誤変換より無変換のほうがよい） ---
  if (/^[\s]*[🎵🎶♪♫♬]/u.test(raw)) return raw; // 音符で始まる歌詞行
  if (/^　/.test(raw)) return raw; // 全角スペース字下げは歌詞・引用
  // 自分の文と併記された「>」の引用行は他人の発言なので触らない
  if (opts.partialQuote && QUOTE_LINE.test(raw)) return raw;
  if (COMMA_END.test(raw)) return raw; // 読点で終わる行は述語が次の行に続く
  // 格助詞で始まる行は前の行の続き（「…- 納品物を受け取る」＋「が自然そう」）。
  // 格助詞の直後を漢字・カタカナに限るのは「がんばる」のような語頭の仮名と
  // 区別するためなのだ
  if (/^[がをにへ][一-龯々ァ-ヺ]/u.test(raw.trim())) return raw;
  if (HEADING_MARK.test(raw)) return raw; // 「■ 流速計測」等の見出しラベル行
  if (/^\s*[[［【（(].*[\]］】）)]\s*$/u.test(raw)) return raw; // 括弧だけの見出し・ラベル行
  if (/([ぁ-ゖァ-ヺ])\1\1/u.test(raw)) return raw; // 同じ仮名の3連続は擬音・叫び
  // 2〜3文字のまとまりが3回以上繰り返される行は擬音（「のすのすのすのす」）。
  // 意味のある語がこの形で3回続くことはないのだ
  if (/^([ぁ-ゖァ-ヺ]{2,3})\1{2,}$/u.test(raw.trim())) return raw;
  if (GREETING.test(raw.trim())) return raw; // 挨拶はそのまま
  if (SHORT_ELONGATED.test(raw.trim())) return raw; // 引き伸ばしただけの短い語はそのまま
  // 波ダッシュを語中に含む短いひらがなの断片は擬音（「うにょ〜ん」「ぷわ〜ん」）。
  // 長音符「ー」は「うまかったー」「ノーマン」のように語の一部でもあるので、
  // ここでは波ダッシュだけを手掛かりにするのだ
  if (/^[ぁ-ゖ][ぁ-ゖー〜～]{0,5}$/u.test(raw.trim()) && /[〜～]/u.test(raw))
    return raw;
  // 1〜2文字のひらがなだけの文は擬音・掛け声（「ぴ」「にゃ」）
  if (/^[ぁ-ゖ]{1,2}$/u.test(raw.trim())) return raw;
  // 半角記号の箇条書きは体言止めの断片が多いので控えめに扱う
  if (ASCII_BULLET.test(raw)) quoted = true;
  // 行単位の手掛かりで「文ではない」と分かった行はそのまま残す
  // （列挙ブロック・字下げ・区切り記号の行・次行が格助詞で始まる行）
  if (opts.skipLines && opts.skipLines.has(raw)) return raw;

  // 読点の前が丁寧語で終わっていれば、そこは文の切れ目なので先に常体へ直してから
  // 残りを処理する（「ねます、おやすみ〜」→「ねるのだ、おやすみなのだ〜」）。
  // 丁寧語に限るのは、「ロボからすると、」「そうそう、」のような普通の読点まで
  // 文末とみなすと、節の途中で語尾が付いて文が壊れるからなのだ
  const pol = raw.match(/^([^、，\n]*?(?:です|ます|ました|ません|でした)[ねよ]?)([、，])/u);
  if (pol) {
    const head = zundaSentence(pol[1], quoted, opts);
    if (head !== pol[1])
      return zundaSentence(head + pol[2] + raw.slice(pol[0].length), quoted, opts);
  }

  // 日本語同士を挟む空白は句点の代わりなので、そこで区切って文ごとに変換する。
  // 手前の文は quoted 扱い（ルールに当たった時だけ変換）にして、
  // 「明日 東京に行く」の「明日」に語尾が付くような行き過ぎを防ぐ。
  const segs = splitByJapaneseSpace(raw);
  if (segs.length > 1) {
    return segs
      .map(
        (seg, k) =>
          zundaSentence(seg.body, k < segs.length - 1 ? true : quoted, opts) +
          seg.gap,
      )
      .join("");
  }

  // 末尾の注記（対応の取れた括弧）を装飾として切り離す
  let note = "";
  let s = raw;
  const nm = s.match(TRAILING_NOTE);
  if (nm) {
    note = nm[0];
    s = s.slice(0, s.length - note.length);
  }
  // 末尾の装飾を切り離してから語尾を変換し、装飾を戻す
  const m = s.match(DECOR_TAIL);
  let decorSym = m ? m[0] : "";
  let core = decorSym ? s.slice(0, s.length - decorSym.length) : s;
  if (!core) return raw; // 日本語コンテンツが無い行はそのまま
  // 日本語に直に続く英数字は語の一部なので本文に戻す（「手仕込みUDP」「衣80%」）。
  // 切り離したままだと語尾が語の途中に入って「手仕込みなのだUDP」になるのだ。
  // 「おもしろいw」の笑いは語ではないので対象外にする
  if (/^[A-Za-z0-9%％]+$/u.test(decorSym) && !/^[wWｗ]+$/u.test(decorSym) &&
      JP_CHAR.test(core[core.length - 1])) {
    core += decorSym;
    decorSym = "";
  }
  if (ONOMATOPOEIA.test(core)) return raw; // 引き伸ばした擬音はそのまま
  // 小書き仮名の引き伸ばしは、語尾を復元できる形のときだけ剥がして変換する
  let smallTail = "";
  if (STRETCH_TAIL.test(core)) {
    const bare = core.replace(/[ぁぃぅぇぉ]+$/u, "");
    if (!bare || !STRETCH_RESTORABLE.test(bare)) return raw;
    smallTail = core.slice(bare.length);
    core = bare;
  }
  const decor = smallTail + decorSym + note;

  // 「ラベル: 値」形式のデータ行（bot の集計・計測ログ）は表を壊すので変換しない
  if (/[:：]/.test(decor)) return raw;
  // 本文の後ろに「演算子＋数字」が続く行は数式・箇条書き風の断片（「らん漫 * 2」）。
  // ここに語尾を挿し込むと式が分断されるのだ。
  // 「らんまん * 4 = らん漫」のように本文が行末に来る形は装飾が空なので影響しない
  if (/^[ \t　]*[-+*/=×÷][ \t　]*[0-9０-９]/u.test(decor)) return raw;
  // 括弧の内側に語尾を挿し込まない
  if (hasUnclosedBracket(core)) return raw;
  // 感動詞・掛け声はそのまま
  if (INTERJECTION.test(core.trim())) return raw;
  // 注記や記号を外したら挨拶だけが残る行はそのまま（「おはようございますのすし(￣^￣)ゞ」）
  if (GREETING.test(core.trim())) return raw;

  // ひらがな＋長音で引き伸ばした感動詞・形容動詞語幹（「いやー」「やだー」）は
  // 長音を落としてから語尾を付ける（「いやーなのだ」の語尾衝突を防ぐ）。
  // 「コーヒー」「インイヤー」のようなカタカナ語の長音は語の一部なので落とさない。
  core = core.replace(/([ぁ-ゖ])ー+$/u, "$1");

  // この投稿の話者のキャラ語尾が付いていれば、その直前の終助詞ごと落としてから
  // 通常の変換にかける（「みたいぷく」→「みたいなのだ」）
  if (opts.charSuffix && core.length > opts.charSuffix.length &&
      core.endsWith(opts.charSuffix)) {
    const bare = core.slice(0, -opts.charSuffix.length).replace(/[ねよなわぞぜ]$/u, "");
    if (bare) core = bare;
  }

  for (const [re, rep] of ZUNDA_RULES) {
    if (re.test(core)) return core.replace(re, rep) + decor;
  }
  // 引用ブロック内でルール非該当の行は歌詞の一節・商品名・擬音なので触らない
  // （「名物かまど」→「名物かまどなのだ」「テロッテ～ン♪」の破壊を防ぐ）
  if (quoted) return raw;
  // ルール非該当時は末尾の文字種で出し分ける
  // 「つ」は漢字の直後だけ用言とみなす（「打つ」は動詞だが「やつ」「星2つ」は体言）
  if (/[一-龯々]つ$|[うくぐすずぬふぶむるいた]$/u.test(core))
    return core + "のだ" + decor; // 用言の終止形
  if (/[らかせへ]ん$/u.test(core)) return core + "のだ" + decor; // 口語否定「〜らん/〜かん」
  // 音符で終わる体言止めの行は歌詞・CM・時報の擬音なので触らない
  // （「ポォ～ン♪」→「ポォ～ンなのだ♪」の破壊を防ぐ。「楽しかった♪」は上の用言で変換済み）
  if (NOTE_TAIL.test(raw)) return raw;
  // 末尾に URL が付く行は共有・告知の定型行で、本文は作品名や見出しのことが多い
  // （「荒野の七人／真昼の決闘 https://…」）。
  // 末尾に括弧の注記が付く行の本文も、作品名や形態名のことが多い
  // （「ゆうひかげ(じょうもんのすがた)」）。
  // どちらも用言で終わる普通の文は上で変換済みなので、残った体言止めには付けないのだ
  if (decor.includes(URL_MARK) || note) return raw;
  // 日本語に英数字が続く語（「手仕込みUDP」「衣80%」）は体言扱い
  if (/[A-Za-z0-9%％]$/u.test(core) && JP_CHAR.test(core))
    return core + "なのだ" + decor;
  if (/[ぁ-ゖ]$/u.test(core)) return core + "なのだ" + decor; // その他の仮名は体言扱い
  if (/[一-龯々ァ-ヺーゝゞ]$/u.test(core)) return core + "なのだ" + decor; // 漢字・カタカナ（体言）
  return core + decor; // それ以外はそのまま
}

function zundamonize(text) {
  // 投稿全体が助詞で始まる短い断片なら、前の投稿の続きなので触らない
  if (FRAGMENT_POST.test(text.trim())) return text;
  // 投稿全体がひらがなだけの短い語なら、挨拶・造語・擬音（「おはのす」「ぴ」）。
  // 挨拶を語彙リストで数え上げるとキリがないので、長さで一般に逃がすのだ
  if (/^[ぁ-ゖ]{1,4}$/u.test(text.trim())) return text;


  // 音符で始まる行（歌詞・CM）か、見出し行（bot の定型投稿）が1行でもあれば、
  // 投稿全体を引用ブロックとみなす。
  // 引用中は用言・丁寧語の行だけ変換し、体言止めの行はそのまま残す。
  const quoted = LYRIC_LINE.test(text) || BOT_HEADING.test(text);

  // URL とハッシュタグは変換から保護する（タグ文字列を壊さないため）
  const kept = [];
  const hold = (mark) => (m) => {
    kept.push(m);
    return mark + (kept.length - 1) + mark;
  };
  let masked = text.replace(/https?:\/\/\S+/g, hold(URL_MARK));
  masked = masked.replace(
    /(^|[\s（(【「])([#＃][^\s#＃]+)/gu,
    (_m, pre, tag) => pre + hold(TAG_MARK)(tag),
  );

  // 材料・データの列挙ブロックに属する行を先に洗い出しておく。
  // 下の分割はマスク後の文字列を渡すので、こちらもマスク後で数えるのだ
  const skipLines = linesToSkip(masked);
  const charSuffix = detectCharSuffix(masked);
  // 引用行と自分の文が混在しているか（＝引用を保護すべきか）
  const bodyLines = masked.split("\n").filter((l) => l.trim() !== "");
  const quoteCount = bodyLines.filter((l) => QUOTE_LINE.test(l)).length;
  const partialQuote = quoteCount > 0 && quoteCount < bodyLines.length;

  // 文単位で分割（句読点・改行を区切りとして保持）し、各文を全部変換する
  // 全角ピリオド「．」を句点として使う書き手もいるので区切りに入れる
  const parts = masked.split(/(\n|。|．|！|!|？|\?)/);
  let out = "";
  for (let i = 0; i < parts.length; i += 2) {
    const body = parts[i] ?? "";
    const delim = parts[i + 1] ?? "";
    if (body.trim() === "") {
      out += body + delim;
      continue;
    }
    let conv = zundaSentence(body, quoted, { skipLines, partialQuote, charSuffix });
    let d = delim;
    // 「〜か。」を疑問化すると「〜のだ？。」と終端記号が重なるので、
    // 変換後が疑問符で終わるなら区切りの句点・疑問符を落とす
    if (/[？?]$/.test(conv) && /^[。？?]$/.test(d)) d = "";
    out += conv + d;
  }

  // URL・ハッシュタグを復元
  return out.replace(
    new RegExp(`[${URL_MARK}${TAG_MARK}](\\d+)[${URL_MARK}${TAG_MARK}]`, "g"),
    (_, i) => kept[Number(i)],
  );
}

export { zundamonize, zundaSentence, ZUNDA_RULES };
