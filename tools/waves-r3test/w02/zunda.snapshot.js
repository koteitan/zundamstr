  // 「乗りなさいのだ」という非文になるのだ。
  // 連用形かどうかは「ください」と同じ3つの条件で確かめるのだ
  // （え段＝一段確定／五段の表／上一段の表／サ変の「し」）。
  // 表で行が決まらない仮名は語の切れ目が読めないので触らない
  // （「これをみなさい」の「み」は五段の表にも上一段の表にも無いので「むのだ」を防ぐ）。
  // 「おやすみなさい」「おかえりなさい」は挨拶として1語になっていて命令ではないのだ。
