      // 接頭辞「お／ご」が文末の文節の中にあるか。
      // 「お」から語尾までの字数では切らないのだ。接頭辞が付く先は複合動詞でもよく
      // （「お問い合わせ」「お召し上がり」「お買い求め」「お受け取り」）、
      // 語幹の長さに上限が無いからなのだ。字数で切ると、その数を超えた語だけが
